// Joins all migrations into supabase/setup.sql, for pasting into the Supabase SQL editor in one go.
import fs from 'node:fs'

const dir = new URL('./migrations/', import.meta.url)
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
const out = files.map((f) => `-- ==== ${f} ====\n${fs.readFileSync(new URL(f, dir), 'utf8')}`).join('\n\n')
fs.writeFileSync(new URL('./setup.sql', import.meta.url), `-- Generated by npm run db:bundle. Do not edit; edit supabase/migrations instead.\n\n${out}`)
console.log(`supabase/setup.sql written from ${files.length} migrations`)
